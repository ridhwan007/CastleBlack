"""
Executive Summary Reporter.

Produces a concise risk overview + top findings for non-technical leadership.
"""

from __future__ import annotations

from collections import Counter
from dataclasses import dataclass, field
from datetime import datetime, timezone
from typing import Any


@dataclass
class ExecutiveSummary:
    engagement_id:   str
    engagement_name: str
    generated_at:    str
    risk_rating:     str          # CRITICAL | HIGH | MEDIUM | LOW | PASS
    total_findings:  int
    by_severity:     dict[str, int]
    critical_hosts:  list[str]
    top_findings:    list[dict]
    narrative:       str
    remediation_pct: float        # % of findings already CLOSED


class ExecutiveReporter:
    """
    Builds an executive summary from a list of Finding dicts.
    """

    RISK_ORDER = ["CRITICAL", "HIGH", "MEDIUM", "LOW", "INFO"]

    def generate(
        self,
        findings: list[dict],
        engagement_id: str,
        engagement_name: str = "Penetration Test",
    ) -> ExecutiveSummary:
        total         = len(findings)
        by_sev        = Counter(f.get("severity", "INFO") for f in findings)
        closed        = sum(1 for f in findings if f.get("status") == "CLOSED")
        remediation_pct = (closed / total * 100) if total else 100.0

        risk_rating   = self._overall_risk(by_sev)
        top_findings  = self._top_findings(findings, n=5)
        critical_hosts = list({
            f["target_host"]
            for f in findings
            if f.get("severity") in ("CRITICAL", "HIGH") and f.get("target_host")
        })

        narrative = self._build_narrative(
            engagement_name=engagement_name,
            total=total,
            by_sev=dict(by_sev),
            risk_rating=risk_rating,
            remediation_pct=remediation_pct,
            critical_hosts=critical_hosts,
        )

        return ExecutiveSummary(
            engagement_id=engagement_id,
            engagement_name=engagement_name,
            generated_at=datetime.now(timezone.utc).isoformat(),
            risk_rating=risk_rating,
            total_findings=total,
            by_severity=dict(by_sev),
            critical_hosts=critical_hosts,
            top_findings=top_findings,
            narrative=narrative,
            remediation_pct=round(remediation_pct, 1),
        )

    def to_markdown(self, summary: ExecutiveSummary) -> str:
        sev_table = "\n".join(
            f"| {sev} | {summary.by_severity.get(sev, 0)} |"
            for sev in self.RISK_ORDER
        )
        top_rows = "\n".join(
            f"| {f.get('id','')} | {f.get('title','')} | "
            f"{f.get('severity','')} | {f.get('cvss_score','')} | {f.get('target_host','')} |"
            for f in summary.top_findings
        )
        hosts = ", ".join(summary.critical_hosts) if summary.critical_hosts else "None"

        return f"""# Executive Summary — {summary.engagement_name}

**Engagement ID:** {summary.engagement_id}
**Generated:**     {summary.generated_at}
**Overall Risk:**  {summary.risk_rating}

---

## Risk Overview

| Severity | Count |
|----------|-------|
{sev_table}
| **Total** | **{summary.total_findings}** |

**Remediation Progress:** {summary.remediation_pct:.1f}% of findings closed.

## Critical / High-Risk Hosts

{hosts}

## Top Findings

| ID | Title | Severity | CVSS | Target |
|----|-------|----------|------|--------|
{top_rows}

---

## Narrative

{summary.narrative}

---
*Generated by AIPTT — Autonomous Internal Penetration Testing Tool*
"""

    # ------------------------------------------------------------------
    # Helpers
    # ------------------------------------------------------------------

    def _overall_risk(self, by_sev: Counter) -> str:
        if by_sev.get("CRITICAL", 0) > 0:
            return "CRITICAL"
        if by_sev.get("HIGH", 0) > 0:
            return "HIGH"
        if by_sev.get("MEDIUM", 0) > 0:
            return "MEDIUM"
        if by_sev.get("LOW", 0) > 0:
            return "LOW"
        return "PASS"

    def _top_findings(self, findings: list[dict], n: int = 5) -> list[dict]:
        return sorted(
            findings,
            key=lambda f: (
                self.RISK_ORDER.index(f.get("severity", "INFO"))
                if f.get("severity", "INFO") in self.RISK_ORDER else 99,
                -(f.get("cvss_score") or 0),
            ),
        )[:n]

    @staticmethod
    def _build_narrative(
        engagement_name: str,
        total: int,
        by_sev: dict,
        risk_rating: str,
        remediation_pct: float,
        critical_hosts: list[str],
    ) -> str:
        crit  = by_sev.get("CRITICAL", 0)
        high  = by_sev.get("HIGH", 0)
        med   = by_sev.get("MEDIUM", 0)

        parts = [
            f"The penetration test of **{engagement_name}** identified a total of "
            f"**{total} finding(s)** with an overall risk rating of **{risk_rating}**."
        ]

        if crit > 0:
            parts.append(
                f"**{crit} critical finding(s)** require immediate attention as they "
                f"represent a high likelihood of significant business impact if exploited."
            )
        if high > 0:
            parts.append(
                f"**{high} high-severity finding(s)** should be remediated within 30 days."
            )
        if med > 0:
            parts.append(
                f"**{med} medium-severity finding(s)** should be addressed within 90 days."
            )

        if critical_hosts:
            host_str = ", ".join(critical_hosts[:3])
            if len(critical_hosts) > 3:
                host_str += f" and {len(critical_hosts) - 3} more"
            parts.append(
                f"Hosts presenting the highest risk include: **{host_str}**."
            )

        if remediation_pct > 0:
            parts.append(
                f"{remediation_pct:.0f}% of findings have already been marked as closed "
                f"following initial remediation efforts."
            )

        return "\n\n".join(parts)
