"""
Reproduction Guide Generator.

FR-PROOF-03: Every confirmed finding must have a structured reproduction guide
             that allows a human to manually verify the vulnerability.
"""

from __future__ import annotations

from dataclasses import dataclass

from jinja2 import Template

# Techniques whose PoE artefacts are time-limited (tokens/tickets expire)
TIME_LIMITED_TECHNIQUES = {"T1134", "T1558.003", "T1558.004", "T1649"}

REPRO_TEMPLATE = Template("""\
# Reproduction Guide — {{ finding_id }}

## Finding Overview
| Field | Value |
|-------|-------|
| Finding ID | {{ finding_id }} |
| Classification | {{ classification }} |
| MITRE Technique | {{ technique }} |
| Module | {{ module_id }} |
| Target | {{ target }} |
| Severity (CVSS) | {{ cvss }} |

## Description
{{ description }}

## Prerequisites
{% for prereq in prerequisites %}
- {{ prereq }}
{% endfor %}

## Reproduction Steps
{% for i, step in steps %}
{{ i }}. {{ step }}
{% endfor %}

## Expected Output
```
{{ expected_output }}
```

{% if time_limited %}
> **WARNING — Time-Limited Artefact**
> This finding involves technique `{{ technique }}` whose proof artefacts
> (tokens/Kerberos tickets) have a limited validity window.
> Reproduce promptly; artefacts may no longer be valid after expiry.
{% endif %}

## Remediation
{{ remediation }}

## References
{% for ref in references %}
- {{ ref }}
{% endfor %}

---
*Generated by AIPTT — Autonomous Internal Penetration Testing Tool*
*Finding captured: {{ timestamp }}*
""")


@dataclass
class ReproGuide:
    finding_id: str
    technique: str
    module_id: str
    target: str
    classification: str
    cvss: float
    time_limited: bool
    markdown: str


class ReproGuideGenerator:
    """
    Generates Jinja2-rendered markdown reproduction guides for confirmed findings.

    Business Rule: Time-limited artefact warning injected for T1134, T1558.003,
                   T1558.004, T1649 (tokens/tickets expire).
    """

    def generate(self, task, result, finding_id: str, classification: str) -> ReproGuide:
        """Render a reproduction guide for a finding."""
        from datetime import datetime, timezone

        technique  = getattr(task, "technique",    "Unknown")
        module_id  = getattr(task, "module_id",    "unknown")
        target     = getattr(task, "target",       "unknown")
        cvss       = getattr(result, "cvss_score", 0.0)

        time_limited = technique in TIME_LIMITED_TECHNIQUES

        steps, prerequisites, references = self._build_content(
            technique, module_id, result
        )
        description     = self._build_description(technique, result)
        remediation     = self._build_remediation(technique)
        expected_output = self._truncate(
            getattr(result, "output", "No output captured."), 500
        )

        markdown = REPRO_TEMPLATE.render(
            finding_id=finding_id,
            classification=classification,
            technique=technique,
            module_id=module_id,
            target=target,
            cvss=cvss,
            description=description,
            prerequisites=prerequisites,
            steps=list(enumerate(steps, start=1)),
            expected_output=expected_output,
            time_limited=time_limited,
            remediation=remediation,
            references=references,
            timestamp=datetime.now(timezone.utc).isoformat(),
        )

        return ReproGuide(
            finding_id=finding_id,
            technique=technique,
            module_id=module_id,
            target=target,
            classification=classification,
            cvss=cvss,
            time_limited=time_limited,
            markdown=markdown,
        )

